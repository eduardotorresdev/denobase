/**
 * Writes src/http/ui_assets.ts from ui/: the package served from JSR has no files to read, so the admin UI and the
 * OAuth page assets travel inside a module. Run `deno task embed-ui` after changing anything under ui/.
 */
import { encodeBase64 } from "@std/encoding/base64";
import { uiContentType } from "../src/http/ui_source.ts";

export const UI_DIR: URL = new URL("../ui/", import.meta.url);
export const OUTPUT: URL = new URL("../src/http/ui_assets.ts", import.meta.url);

async function walk(dir: URL, prefix = ""): Promise<string[]> {
  const out: string[] = [];
  for await (const e of Deno.readDir(dir)) {
    const rel = prefix + e.name;
    if (e.isDirectory) out.push(...await walk(new URL(`${e.name}/`, dir), `${rel}/`));
    else if (e.isFile) out.push(rel);
  }
  return out;
}

/** The source of ui_assets.ts for the files under a UI dir, sorted by path so the output is stable. */
export async function renderUiAssets(dir: URL = UI_DIR): Promise<string> {
  const paths = (await walk(dir)).sort();
  const lines = [
    "// Generated by scripts/embed_ui.ts from ui/ (deno task embed-ui). Do not edit.",
    "",
    "/** The ui/ files by path relative to ui/: content type and base64 bytes. */",
    "export const UI_ASSETS: Record<string, { type: string; data: string }> = {",
  ];
  for (const p of paths) {
    const data = encodeBase64(await Deno.readFile(new URL(p, dir)));
    lines.push(`  ${JSON.stringify(p)}: { type: ${JSON.stringify(uiContentType(p))}, data: ${JSON.stringify(data)} },`);
  }
  lines.push("};", "");
  return lines.join("\n");
}

if (import.meta.main) {
  await Deno.writeTextFile(OUTPUT, await renderUiAssets());
  console.log(`wrote ${decodeURIComponent(OUTPUT.pathname)}`);
}
